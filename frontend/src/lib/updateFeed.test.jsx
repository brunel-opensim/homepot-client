import { describe, it, expect } from 'vitest';

import { parseChecksums, parseUpdateFeed, verifyCommand } from '@/lib/updateFeed';

/**
 * The Downloads page reads the electron-builder update feed at runtime instead
 * of hardcoding version numbers. A parser bug would surface as a missing or
 * wrong download link, so the feed shapes are pinned here against the real
 * files published for this project.
 */

const WINDOWS_FEED = `version: 0.3.0
files:
  - url: homepot-agent-setup-0.3.0.exe
    sha512: wawin3Y2jTu0it5l1KaI0IgH7iXm37iPqdCKW7IT4h7Pr+BpOMo4hCdWxJ8F899KBmHg/4iJgNMpP5zxCAkOtQ==
    size: 128115209
path: homepot-agent-setup-0.3.0.exe
sha512: wawin3Y2jTu0it5l1KaI0IgH7iXm37iPqdCKW7IT4h7Pr+BpOMo4hCdWxJ8F899KBmHg/4iJgNMpP5zxCAkOtQ==
releaseDate: '2026-10-21T07:55:54.352Z'
`;

describe('parseUpdateFeed', () => {
  it('reads the version from the real Windows feed', () => {
    expect(parseUpdateFeed(WINDOWS_FEED).version).toBe('0.3.0');
  });

  it('reads every file entry with its size', () => {
    expect(parseUpdateFeed(WINDOWS_FEED).files).toEqual([
      { url: 'homepot-agent-setup-0.3.0.exe', size: 128115209 },
    ]);
  });

  it('lists multiple artifacts when the feed contains several', () => {
    const feed = `version: 0.3.0
files:
  - url: homepot-agent-0.3.0.dmg
    sha512: abc
    size: 100
  - url: homepot-agent-0.3.0-arm64.dmg
    sha512: def
    size: 200
path: homepot-agent-0.3.0.dmg
`;
    expect(parseUpdateFeed(feed).files).toEqual([
      { url: 'homepot-agent-0.3.0.dmg', size: 100 },
      { url: 'homepot-agent-0.3.0-arm64.dmg', size: 200 },
    ]);
  });

  it('falls back to the path entry when there is no files block', () => {
    const feed = `version: 0.2.0
path: homepot-agent-setup-0.2.0.exe
sha512: abc
size: 99
`;
    const parsed = parseUpdateFeed(feed);
    expect(parsed.version).toBe('0.2.0');
    expect(parsed.files).toEqual([{ url: 'homepot-agent-setup-0.2.0.exe', size: 99 }]);
  });

  it('strips quotes from quoted values', () => {
    const feed = `version: '1.2.3'
path: 'some-installer.exe'
`;
    const parsed = parseUpdateFeed(feed);
    expect(parsed.version).toBe('1.2.3');
    expect(parsed.files[0].url).toBe('some-installer.exe');
  });

  it('returns an empty result for empty or missing input', () => {
    expect(parseUpdateFeed('')).toEqual({ version: null, files: [] });
    expect(parseUpdateFeed(null)).toEqual({ version: null, files: [] });
  });

  it('does not invent files when the feed has only a version', () => {
    const parsed = parseUpdateFeed('version: 0.3.0\nreleaseDate: today\n');
    expect(parsed.version).toBe('0.3.0');
    expect(parsed.files).toEqual([]);
  });

  it('parses nothing useful out of an HTML response', () => {
    // Missing files on this host are rewritten to index.html by the SPA
    // fallback and return 200, so the page must reject an HTML body rather
    // than scrape a "version" out of markup.
    const html = `<!doctype html>
<html lang="en">
  <head><title>homepot</title></head>
  <body><div id="root"></div></body>
</html>
`;
    const parsed = parseUpdateFeed(html);
    expect(parsed.version).toBeNull();
    expect(parsed.files).toEqual([]);
  });
});

/**
 * checksums.json is generated by the packaging job from the exact published
 * bytes. The page only ever displays a digest it read from here, so the parser
 * must reject anything that is not a real 64-character SHA-256 -- showing a
 * truncated or malformed digest would be worse than showing none.
 */

const SHA256 = '749d4bdb2b33d17c1bb15351da93a67386180ab9f2eff55e65debba9012d2720';
const SHA512 =
  'wawin3Y2jTu0it5l1KaI0IgH7iXm37iPqdCKW7IT4h7Pr+BpOMo4hCdWxJ8F899KBmHg/4iJgNMpP5zxCAkOtQ==';

const CHECKSUMS = JSON.stringify({
  files: {
    'homepot-agent-setup-0.3.0.exe': { size: 128115209, sha256: SHA256, sha512: SHA512 },
  },
});

describe('parseChecksums', () => {
  it('reads the sha256, sha512 and size for an artifact', () => {
    expect(parseChecksums(CHECKSUMS)).toEqual({
      'homepot-agent-setup-0.3.0.exe': {
        sha256: SHA256,
        sha512: SHA512,
        size: 128115209,
      },
    });
  });

  it('lowercases the digest so comparisons are stable', () => {
    const manifest = JSON.stringify({
      files: { 'a.exe': { sha256: SHA256.toUpperCase() } },
    });
    expect(parseChecksums(manifest)['a.exe'].sha256).toBe(SHA256);
  });

  it('returns an empty map for missing, empty or non-JSON input', () => {
    // An absent manifest is not an error: the page degrades to no checksum.
    expect(parseChecksums('')).toEqual({});
    expect(parseChecksums(null)).toEqual({});
    expect(parseChecksums('<!doctype html><html></html>')).toEqual({});
  });

  it('drops entries whose sha256 is malformed', () => {
    const manifest = JSON.stringify({
      files: {
        'good.exe': { sha256: SHA256 },
        'truncated.exe': { sha256: SHA256.slice(0, 40) },
        'not-hex.exe': { sha256: 'z'.repeat(64) },
        'missing.exe': { size: 123 },
        'wrong-type.exe': { sha256: 12345 },
        'null.exe': null,
      },
    });
    expect(Object.keys(parseChecksums(manifest))).toEqual(['good.exe']);
  });

  it('ignores a manifest that lacks a files object', () => {
    expect(parseChecksums('{"version": 1}')).toEqual({});
    expect(parseChecksums('{"files": []}')).toEqual({});
  });
});

describe('verifyCommand', () => {
  it('gives the native hashing command for each platform', () => {
    expect(verifyCommand('windows', 'setup.exe')).toBe('certutil -hashfile "setup.exe" SHA256');
    expect(verifyCommand('macos', 'app.dmg')).toBe('shasum -a 256 ~/Downloads/app.dmg');
    expect(verifyCommand('linux', 'app.AppImage')).toBe('sha256sum ~/Downloads/app.AppImage');
  });

  it('falls back to sha256sum for an unknown platform', () => {
    expect(verifyCommand('unknown', 'file.bin')).toBe('sha256sum file.bin');
  });
});
